// Checked-in HTML generation: no browser request, runtime import or UI change.
const fs = require('node:fs');
const path = require('node:path');
const { activeJobTypes } = require('../utils/yannisTaxonomies');
const ROOT = path.resolve(__dirname, '../..');
const FILES = ['frontend/_spaces/candidat.html', 'frontend/_spaces/recruteur.html'];
const escapeHtml = text => text.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const quoteJs = text => "'" + text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/</g, '\\u003c') + "'";

function replaceOne(source, pattern, replacement) {
  const matches = [...source.matchAll(new RegExp(pattern.source, 'g'))];
  if (matches.length !== 1) throw new Error(`Expected one taxonomy anchor: ${pattern.source}`);
  return source.replace(pattern, replacement);
}
function render(file, input) {
  const newline = input.includes('\r\n') ? '\r\n' : '\n';
  let text = input.replace(/\r\n/g, '\n');
  const jobs = activeJobTypes();
  for (const job of jobs) {
    if (!/^[a-z][a-z0-9_]*$/.test(job.id)) throw new Error('Unsafe job ID');
  }
  if (file === FILES[0]) {
    text = replaceOne(text, /(<div class="opts" id="job-type-opts">)[\s\S]*?(\n      <\/div>)/, (_all, start, end) =>
      start + '\n        <!-- Generated by sync-job-taxonomy.js: ADN job IDs -->\n' + jobs.map(job =>
        `        <button class="opt" onclick="selectJobType('${job.id}',this)"><span class="ot">${escapeHtml(job.label)}</span></button>`).join('\n') + end);
    text = replaceOne(text, /(const PROFILE_PREF_SUGGESTIONS = Object.freeze\(\{\n  target_job_types: \[)[\s\S]*?(\n  \],)/, (_all, start, end) =>
      start + '\n    // Generated by sync-job-taxonomy.js: persisted labels\n    ' + jobs.map(job => quoteJs(job.label)).join(', ') + ',' + end);
    // Questions themselves stay untouched. Adding an ADN job requires an explicit
    // question module: fail instead of silently submitting an incomplete test.
    const start = text.indexOf('const PROFILE_QUESTIONS = {');
    const end = text.indexOf('let TEST_JOB_TYPE', start);
    if (start < 0 || end < 0) throw new Error('Missing ADN question anchor');
    let questions = text.slice(start, end);
    for (const job of jobs) {
      questions = replaceOne(questions, new RegExp(`(  ${job.id}: \\{\\n    label: )` + /'(?:\\.|[^'\\\n])*'/.source), (_all, prefix) => prefix + quoteJs(job.label));
    }
    text = text.slice(0, start) + questions + text.slice(end);
  } else if (file === FILES[1]) {
    text = replaceOne(text, /(<div class="form-chips" id="filt-job-types">)[\s\S]*?(\n      <\/div>)/, (_all, start, end) =>
      start + '\n        <!-- Generated by sync-job-taxonomy.js: sourcing labels -->\n' + jobs.map(job =>
        `        <button type="button" class="form-chip" data-filter-value="${escapeHtml(job.label)}" onclick="toggleCandFilterChip(this)">${escapeHtml(job.label)}</button>`).join('\n') + end);
  } else throw new Error('Unknown taxonomy consumer');
  return text.replace(/\n/g, newline);
}
function sync({ write = false } = {}) {
  for (const file of FILES) {
    const filename = path.join(ROOT, file);
    const current = fs.readFileSync(filename, 'utf8');
    const expected = render(file, current);
    if (current === expected) continue;
    if (!write) throw new Error(`${file}: run npm --prefix backend run taxonomy:sync`);
    fs.writeFileSync(filename, expected, 'utf8');
  }
}
if (require.main === module) {
  sync({ write: process.argv.includes('--write') });
  console.log('Job taxonomy HTML is synchronized');
}
module.exports = { FILES, render, sync };
